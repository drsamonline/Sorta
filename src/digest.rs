//! Weekly digest.
//!
//! A Markdown summary of what Sorta did over a window of days, built only from
//! the append-only history. No model, no new state: if the log says it happened,
//! the digest says it happened.
//!
//! The same renderer serves `sorta digest` today and the Monday-09:00
//! notification in a later phase.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use chrono::{DateTime, Duration, Local};

use crate::history::HistoryEntry;

/// A digest ready to print or write.
#[derive(Debug, Clone)]
pub struct Digest {
    pub window_days: i64,
    pub generated_at: String,
    pub markdown: String,
}

impl Digest {
    /// Writes the digest into `dir` and returns the path.
    pub fn write(&self, dir: &Path) -> anyhow::Result<PathBuf> {
        crate::paths::ensure_dir(dir)?;
        let name = format!(
            "digest-{}.md",
            chrono::Local::now().format("%Y-%m-%d")
        );
        let path = dir.join(name);
        std::fs::write(&path, &self.markdown)?;
        Ok(path)
    }
}

/// Builds a digest for the last `window_days` days.
pub fn build(history: &[HistoryEntry], window_days: i64, now: DateTime<Local>) -> Digest {
    let window_days = window_days.max(1);
    let cutoff = now - Duration::days(window_days);

    let in_window: Vec<&HistoryEntry> = history
        .iter()
        .filter(|entry| match entry.timestamp() {
            Some(ts) => ts >= cutoff,
            None => false,
        })
        .collect();

    let mut by_status: BTreeMap<String, usize> = BTreeMap::new();
    let mut by_rule: BTreeMap<String, usize> = BTreeMap::new();
    let mut by_category: BTreeMap<String, usize> = BTreeMap::new();

    for entry in &in_window {
        *by_status.entry(entry.status.clone()).or_insert(0) += 1;
        if entry.status == "committed" || entry.status == "planned" {
            *by_rule.entry(entry.rule.clone()).or_insert(0) += 1;
            *by_category.entry(category_of(&entry.dst)).or_insert(0) += 1;
        }
    }

    let mut md = String::new();
    md.push_str(&format!(
        "# Sorta digest — last {window_days} day(s)\n\n"
    ));
    md.push_str(&format!(
        "Generated {} · {} log entries in the window\n\n",
        now.format("%d %b %Y %H:%M"),
        in_window.len()
    ));

    if in_window.is_empty() {
        md.push_str("Nothing was sorted in this window.\n");
    } else {
        md.push_str("## Outcomes\n\n| Outcome | Files |\n|---|---|\n");
        for (status, count) in &by_status {
            md.push_str(&format!("| {status} | {count} |\n"));
        }
        md.push('\n');

        md.push_str("## Where things went\n\n| Folder | Files |\n|---|---|\n");
        for (category, count) in top(&by_category, 8) {
            md.push_str(&format!("| {category} | {count} |\n"));
        }
        md.push('\n');

        md.push_str("## Rules that decided\n\n| Rule | Files |\n|---|---|\n");
        for (rule, count) in top(&by_rule, 8) {
            md.push_str(&format!("| {rule} | {count} |\n"));
        }
        md.push('\n');

        let unruled = by_status.get("failed").copied().unwrap_or(0)
            + by_status.get("deferred").copied().unwrap_or(0);
        if unruled > 0 {
            md.push_str(&format!(
                "## Needs a look\n\n{unruled} file(s) failed or were deferred. \
                 Run `sorta history` to see why.\n\n"
            ));
        }
    }

    md.push_str("---\n\n");
    md.push_str(&format!(
        "Generated by sorta {}. Undo any of it with `sorta undo --since`.\n",
        crate::VERSION
    ));

    Digest {
        window_days,
        generated_at: now.to_rfc3339(),
        markdown: md,
    }
}

/// The folder a destination path landed in, for the "where things went" table.
fn category_of(dst: &str) -> String {
    let path = Path::new(dst);
    path.parent()
        .and_then(|p| p.file_name())
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_else(|| "(unknown)".to_string())
}

/// Sorts a count map by count descending, then name, and takes the head.
fn top(map: &BTreeMap<String, usize>, n: usize) -> Vec<(String, usize)> {
    let mut items: Vec<(String, usize)> = map.iter().map(|(k, v)| (k.clone(), *v)).collect();
    items.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    items.truncate(n);
    items
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(dst: &str, rule: &str, status: &str, ts: DateTime<Local>) -> HistoryEntry {
        HistoryEntry {
            ts: ts.with_timezone(&chrono::Utc).to_rfc3339(),
            src: "/inbox/x.pdf".to_string(),
            dst: dst.to_string(),
            rule: rule.to_string(),
            confidence: 0.9,
            signals: vec!["keyword".to_string()],
            instance: "default".to_string(),
            hash: "b3:aa".to_string(),
            status: status.to_string(),
        }
    }

    #[test]
    fn summarises_a_week() {
        let now = Local::now();
        let history = vec![
            entry("/data/2026/PDF-Invoices/a.pdf", "keyword:invoice", "committed", now),
            entry("/data/2026/PDF-Invoices/b.pdf", "keyword:invoice", "committed", now),
            entry("/data/2026/Images/c.png", "format:image", "committed", now),
            entry("/data/2026/Text/d.txt", "format:text", "skipped", now),
        ];

        let digest = build(&history, 7, now);
        let md = &digest.markdown;
        assert!(md.contains("last 7 day(s)"));
        assert!(md.contains("| committed | 3 |"));
        assert!(md.contains("| skipped | 1 |"));
        assert!(md.contains("| PDF-Invoices | 2 |"));
        assert!(md.contains("| keyword:invoice | 2 |"));
    }

    #[test]
    fn ignores_entries_outside_the_window() {
        let now = Local::now();
        let history = vec![entry(
            "/data/2026/PDF-Invoices/old.pdf",
            "keyword:invoice",
            "committed",
            now - Duration::days(30),
        )];
        let digest = build(&history, 7, now);
        assert!(digest.markdown.contains("Nothing was sorted"));
    }

    #[test]
    fn empty_history_is_not_an_error() {
        let digest = build(&[], 7, Local::now());
        assert!(digest.markdown.contains("# Sorta digest"));
    }

    #[test]
    fn writes_a_dated_file() {
        let dir = tempfile::tempdir().unwrap();
        let digest = build(&[], 7, Local::now());
        let path = digest.write(dir.path()).unwrap();
        assert!(path.exists());
        assert!(path
            .file_name()
            .unwrap()
            .to_string_lossy()
            .starts_with("digest-"));
    }
}
