//! Receipts.
//!
//! Every run that changes anything writes `_receipts/YYYY-MM-DD-HHMM.md`: what
//! moved, where to, which rule decided, and what was left alone. A receipt is a
//! file the user can keep, diff against yesterday's, or paste into a ticket —
//! which is why it is Markdown and not a log line.

use std::path::{Path, PathBuf};

use crate::pipeline::{Outcome, Status};

/// A rendered receipt, before it hits disk.
#[derive(Debug, Clone)]
pub struct Receipt {
    pub generated_at: String,
    pub destination_root: String,
    pub outcomes: Vec<Outcome>,
    pub dry_run: bool,
}

impl Receipt {
    pub fn new(destination_root: &Path, outcomes: Vec<Outcome>, dry_run: bool) -> Self {
        Self {
            generated_at: chrono::Local::now().to_rfc3339(),
            destination_root: destination_root.display().to_string(),
            outcomes,
            dry_run,
        }
    }

    /// Counts per status label.
    pub fn counts(&self) -> Vec<(String, usize)> {
        let mut out: Vec<(String, usize)> = Vec::new();
        for outcome in &self.outcomes {
            let label = outcome.status.label().to_string();
            match out.iter_mut().find(|(l, _)| *l == label) {
                Some((_, n)) => *n += 1,
                None => out.push((label, 1)),
            }
        }
        out.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
        out
    }

    /// Markdown body.
    pub fn render(&self) -> String {
        let mut md = String::new();
        md.push_str("# Sorta receipt\n\n");
        md.push_str(&format!("- Generated: {}\n", self.generated_at));
        md.push_str(&format!("- Destination root: `{}`\n", self.destination_root));
        if self.dry_run {
            md.push_str("- Mode: **dry run** (nothing was moved)\n");
        }
        md.push('\n');

        md.push_str("## Summary\n\n");
        if self.outcomes.is_empty() {
            md.push_str("No files were considered.\n");
        } else {
            md.push_str("| Outcome | Files |\n|---|---|\n");
            for (label, count) in self.counts() {
                md.push_str(&format!("| {label} | {count} |\n"));
            }
        }
        md.push('\n');

        let moved: Vec<&Outcome> = self
            .outcomes
            .iter()
            .filter(|o| matches!(o.status, Status::Moved | Status::Planned))
            .collect();
        if !moved.is_empty() {
            md.push_str("## Files\n\n");
            md.push_str("| File | Destination | Rule | Confidence |\n|---|---|---|---|\n");
            for outcome in moved {
                let name = Path::new(&outcome.src)
                    .file_name()
                    .map(|n| n.to_string_lossy().to_string())
                    .unwrap_or_else(|| outcome.src.clone());
                let dest = outcome
                    .dst
                    .clone()
                    .unwrap_or_else(|| "(not planned)".to_string());
                md.push_str(&format!(
                    "| {} | `{}` | {} | {:.0}% |\n",
                    escape(&name),
                    escape(&dest),
                    outcome.rule,
                    outcome.confidence * 100.0
                ));
            }
            md.push('\n');
        }

        let attention: Vec<&Outcome> = self
            .outcomes
            .iter()
            .filter(|o| {
                matches!(
                    o.status,
                    Status::Skipped | Status::Duplicate | Status::Quarantined | Status::Failed | Status::Deferred
                )
            })
            .collect();
        if !attention.is_empty() {
            md.push_str("## Left alone, and why\n\n");
            for outcome in attention {
                md.push_str(&format!(
                    "- `{}` — {} ({})\n",
                    escape(&outcome.src),
                    outcome.status.label(),
                    escape(&outcome.note)
                ));
            }
            md.push('\n');
        }

        md.push_str("---\n\n");
        md.push_str(&format!(
            "Generated by sorta {}. Undo with `sorta undo --last {}`.\n",
            crate::VERSION,
            self.outcomes.len()
        ));
        md
    }

    /// Writes the receipt into `<root>/_receipts/` and returns the path.
    pub fn write(&self, root: &Path) -> anyhow::Result<PathBuf> {
        let dir = root.join("_receipts");
        crate::paths::ensure_dir(&dir)?;
        let name = format!("{}.md", chrono::Local::now().format("%Y-%m-%d-%H%M"));
        let path = dir.join(name);
        std::fs::write(&path, self.render())?;
        Ok(path)
    }
}

/// Escapes pipe characters so a filename cannot break the table.
fn escape(text: &str) -> String {
    text.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn outcome(src: &str, dst: Option<&str>, status: Status) -> Outcome {
        Outcome {
            src: src.to_string(),
            dst: dst.map(|d| d.to_string()),
            rule: "keyword:Invoice".to_string(),
            confidence: 0.94,
            signals: vec!["keyword".to_string()],
            status,
            note: String::new(),
        }
    }

    #[test]
    fn renders_a_table_and_a_summary() {
        let receipt = Receipt::new(
            Path::new("/data/Sorted"),
            vec![
                outcome("/inbox/a.pdf", Some("/data/Sorted/2026/a.pdf"), Status::Moved),
                outcome("/inbox/b.pdf", None, Status::Duplicate),
            ],
            false,
        );
        let md = receipt.render();
        assert!(md.contains("# Sorta receipt"));
        assert!(md.contains("| Moved | 1 |"));
        assert!(md.contains("| Duplicate | 1 |"));
        assert!(md.contains("keyword:Invoice"));
        assert!(md.contains("Left alone, and why"));
    }

    #[test]
    fn dry_run_is_labelled() {
        let receipt = Receipt::new(Path::new("/data"), Vec::new(), true);
        assert!(receipt.render().contains("dry run"));
    }

    #[test]
    fn writes_into_receipts_folder() {
        let dir = tempfile::tempdir().unwrap();
        let receipt = Receipt::new(dir.path(), Vec::new(), false);
        let path = receipt.write(dir.path()).unwrap();
        assert!(path.exists());
        assert!(path.parent().unwrap().ends_with("_receipts"));
    }

    #[test]
    fn pipes_in_names_are_escaped() {
        let receipt = Receipt::new(
            Path::new("/data"),
            vec![outcome("/inbox/a|b.pdf", None, Status::Moved)],
            false,
        );
        assert!(receipt.render().contains("a\\|b.pdf"));
    }
}
